// Compile only through scripts/gen-unicode.sh with the pinned Rust SDK.
// One collected semantic data set supplies both compiler evaluation and C runtime.
use std::fmt::Write as _;
use std::path::Path;

const RUST_SOURCE: &str = "5b7b37aefcb5b2fba3c2392bc9065b9e4602d494";
const UNICODE_VERSION: (u8, u8, u8) = (18, 0, 0);

fn ranges(values: &[u32]) -> Vec<(u32, u32)> {
    let mut result: Vec<(u32, u32)> = Vec::new();
    for &value in values {
        match result.last_mut() {
            Some((_, hi)) if *hi + 1 == value => *hi = value,
            _ => result.push((value, value)),
        }
    }
    result
}

fn c_ranges(out: &mut String, name: &str, values: &[u32]) {
    writeln!(out, "static const uint32_t {name}[][2] = {{").unwrap();
    for chunk in ranges(values).chunks(6) {
        out.push_str("    ");
        for &(lo, hi) in chunk {
            write!(out, "{{0x{lo:x}, 0x{hi:x}}}, ").unwrap();
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("};\n");
}

fn rust_ranges(out: &mut String, name: &str, values: &[u32]) {
    writeln!(out, "pub(super) static {name}: &[(u32, u32)] = &[").unwrap();
    for chunk in ranges(values).chunks(6) {
        out.push_str("    ");
        for &(lo, hi) in chunk {
            write!(out, "(0x{lo:x}, 0x{hi:x}), ").unwrap();
        }
        out.pop();
        out.push('\n');
    }
    out.push_str("];\n");
}

fn c_ranges_lines(out: &mut String, name: &str, values: &[u32], case_style: bool) {
    writeln!(out, "static const uint32_t {name}[][2] = {{").unwrap();
    for (lo, hi) in ranges(values) {
        if case_style { writeln!(out, "  {{0x{lo:X}, 0x{hi:X}}},").unwrap(); }
        else { writeln!(out, "    {{0x{lo:x}, 0x{hi:x}}},").unwrap(); }
    }
    out.push_str("};\n");
}

fn c_map(out: &mut String, name: &str, values: &[(u32, Vec<char>)]) {
    writeln!(out, "static const uint32_t {name}[][4] = {{").unwrap();
    for (cp, mapping) in values {
        assert!(!mapping.is_empty() && mapping.len() <= 3);
        let mut mapped = [0u32; 3];
        for (i, &c) in mapping.iter().enumerate() {
            mapped[i] = c as u32;
        }
        writeln!(out, "  {{0x{cp:X}, 0x{:X}, 0x{:X}, 0x{:X}}},", mapped[0], mapped[1], mapped[2]).unwrap();
    }
    out.push_str("};\n");
}

fn main() {
    let args: Vec<_> = std::env::args_os().collect();
    assert_eq!(args.len(), 2, "usage: gen-unicode-semantics OUTPUT_DIRECTORY");
    assert_eq!(char::UNICODE_VERSION, UNICODE_VERSION, "wrong standard-library Unicode semantics");
    assert_eq!(env!("LUSTR_UNICODE_RUST_SOURCE"), RUST_SOURCE, "wrong SDK source");
    let out = Path::new(&args[1]);
    let names = ["alphabetic", "numeric", "lowercase", "uppercase", "whitespace", "control"];
    let mut predicates: [Vec<u32>; 6] = std::array::from_fn(|_| Vec::new());
    let mut upper = Vec::new();
    let mut lower = Vec::new();
    let mut escaped = Vec::new();
    let mut ignorable = Vec::new();
    let mut cased = Vec::new();
    let mut scalar_count = 0;
    for cp in 0..=0x10ffff {
        let Some(c) = char::from_u32(cp) else { continue };
        scalar_count += 1;
        let values = [c.is_alphabetic(), c.is_numeric(), c.is_lowercase(), c.is_uppercase(), c.is_whitespace(), c.is_control()];
        assert_eq!(c.is_alphanumeric(), values[0] || values[1], "U+{cp:04X}");
        for (table, value) in predicates.iter_mut().zip(values) {
            if value { table.push(cp); }
        }
        let up: Vec<char> = c.to_uppercase().collect();
        if up != [c] { upper.push((cp, up)); }
        let lo: Vec<char> = c.to_lowercase().collect();
        if lo != [c] { lower.push((cp, lo)); }
        if c.escape_debug().to_string().starts_with("\\u{") { escaped.push(cp); }
        // These two observations identify the exact effective partition used
        // by upstream str::to_lowercase: case-ignorable takes precedence over
        // cased, including scalars which have both Unicode properties.
        if c == 'Σ' {
            cased.push(cp);
        } else {
            let alone = format!("{c}Σ").to_lowercase().ends_with('ς');
            let preceded = format!("A{c}Σ").to_lowercase().ends_with('ς');
            if preceded && !alone { ignorable.push(cp); }
            else if alone { cased.push(cp); }
        }
    }
    assert_eq!(scalar_count, 1_112_064);
    let header = format!("// Generated by tools/gen_unicode_semantics.rs. Do not edit.\n// Rust source {RUST_SOURCE}; Unicode 18.0.0.\n// Regenerate all consumers together with scripts/gen-unicode.sh.\n");
    let mut rust = header.clone();
    rust.push_str("pub const UNICODE_VERSION: (u8, u8, u8) = (18, 0, 0);\n");
    let mut c = header.clone();
    for (name, values) in names.iter().zip(&predicates) {
        c_ranges(&mut c, &format!("lust_uni_{name}_ranges"), values);
        rust_ranges(&mut rust, &name.to_ascii_uppercase(), values);
    }
    rust_ranges(&mut rust, "ESCAPE", &escaped);
    let mut escape = header.clone();
    c_ranges_lines(&mut escape, "lust_escape_ranges", &escaped, false);
    let mut case = header;
    c_map(&mut case, "lust_upper_map", &upper);
    c_map(&mut case, "lust_lower_map", &lower);
    c_ranges_lines(&mut case, "lust_case_ignorable", &ignorable, true);
    c_ranges_lines(&mut case, "lust_cased", &cased, true);
    std::fs::create_dir_all(out).unwrap();
    for (name, data) in [("unicode_data.rs", rust), ("unicode_table.h", c), ("escape_table.h", escape), ("case_tables.h", case)] {
        std::fs::write(out.join(name), data).unwrap();
    }
    println!("{scalar_count} Unicode scalar values; predicates {:?}; upper mappings {}; lower mappings {}; debug escapes {}; effective sigma ignorable {}; effective sigma cased {}", predicates.each_ref().map(|p| p.len()), upper.len(), lower.len(), escaped.len(), ignorable.len(), cased.len());
}
